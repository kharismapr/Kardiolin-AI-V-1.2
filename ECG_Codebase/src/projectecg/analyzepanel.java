    /**
     * Generate local health advice using Gemini (fallback)
     */
    private String generateLocalAdvice() {
        // BMI calculation removed
        
        // Determine age-specific risk factors
        String ageRiskNote = "";
        if (patientAge > 0) {
            if (patientAge >= 65) {
                ageRiskNote = " Age-related cardiac monitoring recommended.";
            } else if (patientAge >= 45) {
                ageRiskNote = " Regular cardiovascular screening advised.";
            }
        }
        
        String kodeAsli = classificationResult; 
        if (kodeAsli != null) {
            kodeAsli = kodeAsli.trim();
        } else {
            kodeAsli = "Unknown";
        }
        
        // HITUNG ULANG TINGKAT RISIKO 
        String tingkatRisiko = projectecg.GeminiHealthAdvisor.calculateRiskLevel(kodeAsli);

        String konteksPasien = "Risk level: " + tingkatRisiko +
               ", Age: " + patientAge +
               ", Sex: " + patientSex;

        String advice = "";
        // Cek apakah parent adalah MainDashboard, jika iya gunakan saran dari jtxtNotes2
        if (this.getOwner() instanceof projectecg.MainDashboard) {
            projectecg.MainDashboard parent = (projectecg.MainDashboard) this.getOwner();
            String mainAdvice = parent.getHealthAdviceText();
            if (mainAdvice != null && !mainAdvice.trim().isEmpty() && !mainAdvice.contains("No health advice available")) {
                advice = mainAdvice;
                // Bersihkan disclaimer bawaan jtxtNotes2 ("⚠ Consult a cardiologist...") agar tidak double/duplikat
                int disclaimerIdx = advice.indexOf("\n\n⚠");
                if (disclaimerIdx != -1) {
                    advice = advice.substring(0, disclaimerIdx).trim();
                } else {
                    disclaimerIdx = advice.indexOf("⚠");
                    if (disclaimerIdx != -1) {
                        advice = advice.substring(0, disclaimerIdx).trim();
                    }
                }
            }
        }
        
        // Fallback jika tidak berhasil mengambil dari MainDashboard
        if (advice.isEmpty()) {
            // Use ADVANCED GeminiHealthAdvisor for AI-powered advice with risk level context
            advice = projectecg.GeminiHealthAdvisor.generateAdvancedHealthAdvice(
                kodeAsli,     
                confidenceRate,  
                konteksPasien   // <-- PENTING: Gunakan tingkatRisiko yang baru dihitung
            );
        }
        
        // Wrap in professional health report format with clear sections
        StringBuilder report = new StringBuilder();
        report.append("─────────────────────────────────────────────────────────────────────\n");
        report.append("                                                    ECG ANALYSIS REPORT                                             \n");
        
        report.append("\n📊 CLASSIFICATION RESULTS:\n");
        // Gunakan kodeAsli agar menampilkan "N", "V", atau "Other"
        report.append("   Classification: ").append(kodeAsli).append("\n"); 
        report.append("   Description: ").append(projectecg.GeminiHealthAdvisor.getClassificationDescription(kodeAsli)).append("\n");
        report.append("   Confidence: ").append(String.format("%.1f%%", confidenceRate * 100)).append("\n");
        // Gunakan tingkatRisiko agar tidak menampilkan "Unknown"
        report.append("   Risk Level: ").append(tingkatRisiko).append("\n\n");
        
        // NEW: Add patient-specific health context
        report.append("📋 PATIENT HEALTH CONTEXT:\n");
        if (patientAge > 0) {
            report.append("   Age Group: ").append(patientAge).append(" years");
            if (patientAge >= 65) report.append(" (Senior)");
            else if (patientAge >= 45) report.append(" (Middle-aged)");
            else if (patientAge >= 18) report.append(" (Adult)");
            else report.append(" (Young)");
            report.append("\n");
        }
        // BMI-specific advice removed
        
        report.append("\n💡 HEALTH ADVICE:\n");
        report.append("   ").append(advice).append("\n\n");
        
        report.append("─────────────────────────────────────────────────────────────────────\n");
        report.append("                                                                 ⚠  DISCLAIMER:                                                 \n");
        report.append("This advice is for informational purposes only and should not replace professional medical consultation.\n");
        report.append("Please consult with a healthcare professional for clinical decisions and treatment recommendations.\n");
        
        return report.toString();
    }
    
