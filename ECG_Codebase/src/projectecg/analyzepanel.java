    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {
        // Cek apakah ada data analisis
        if (currentAnalyzer == null && classificationResult.equals("N/A")) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "No analysis results to export!\nPlease run analysis first.", 
                "Export Error", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Buat file chooser dialog
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Save ECG Analysis Results");
        
        // Default filename dengan timestamp (tanpa ekstensi dulu)
        String timestamp = new java.text.SimpleDateFormat("yyyyMMdd_HHmmss").format(new java.util.Date());
        String defaultFileName = "ECG_Analysis_" + timestamp;
        fileChooser.setSelectedFile(new java.io.File(defaultFileName));
        
        // Pilihan ekstension (PDF & CSV)
        javax.swing.filechooser.FileNameExtensionFilter filterPDF = new javax.swing.filechooser.FileNameExtensionFilter("PDF Documents (*.pdf)", "pdf");
        javax.swing.filechooser.FileNameExtensionFilter filterCSV = new javax.swing.filechooser.FileNameExtensionFilter("CSV Files (*.csv)", "csv");
        
        fileChooser.addChoosableFileFilter(filterPDF);
        fileChooser.addChoosableFileFilter(filterCSV);
        fileChooser.setFileFilter(filterPDF); // Jadikan PDF sebagai pilihan default (pertama muncul)
        
        // Tampilkan dialog save
        int result = fileChooser.showSaveDialog(this);
        
        if (result == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File selectedFile = fileChooser.getSelectedFile();
            String filePath = selectedFile.getAbsolutePath();
            
            // Cek filter mana yang dipilih oleh user
            javax.swing.filechooser.FileFilter selectedFilter = fileChooser.getFileFilter();
            
            // Jika CSV dipilih
            if (selectedFilter == filterCSV || filePath.toLowerCase().endsWith(".csv")) {
                if (!filePath.toLowerCase().endsWith(".csv")) {
                    filePath += ".csv";
                }
                java.io.File csvFile = new java.io.File(filePath);
                
                // Ambil nilai interval dari Text Field 
                int rPeaks = 0, pPeaks = 0, tPeaks = 0;
                double rrInterval = 0.0, prInterval = 0.0, qtInterval = 0.0, qtcInterval = 0.0;
                
                try {
                    rPeaks = Integer.parseInt(jTextField8.getText());
                    pPeaks = Integer.parseInt(jTextField9.getText());
                    tPeaks = Integer.parseInt(jTextField10.getText());
                    rrInterval = Double.parseDouble(jTextField5.getText());
                    prInterval = Double.parseDouble(jTextField11.getText()) * 1000;  
                    qtInterval = Double.parseDouble(jTextField12.getText()) * 1000;  
                    qtcInterval = Double.parseDouble(jTextField13.getText()) * 1000; 
                } catch (NumberFormatException e) {
                    rPeaks = 75; pPeaks = 74; tPeaks = 75; rrInterval = 833.33;
                    prInterval = 120.0; qtInterval = 400.0; qtcInterval = 410.0;
                }
                
                String healthAdviceText = generateHealthAdvice();
                boolean success = CSVExporter.exportToCSVWithDemographics(
                    csvFile, patientName, patientID, patientSex, patientBirthdate,
                    String.valueOf(patientAge), "-", "-",
                    classificationResult, confidenceRate * 100, riskLevel, 0,  
                    rPeaks, pPeaks, tPeaks, rrInterval, healthAdviceText,
                    prInterval, qtInterval, qtcInterval 
                );
                
                if (success) {
                    javax.swing.JOptionPane.showMessageDialog(this, "✓ CSV saved to:\n" + csvFile.getAbsolutePath(), "Export Successful", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error saving CSV file.", "Export Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            } 
            // Jika PDF dipilih
            else {
                if (!filePath.toLowerCase().endsWith(".pdf")) {
                    filePath += ".pdf";
                }
                
                try {
                    projectecg.MainDashboard parent = (projectecg.MainDashboard) this.getParent();

                    // 1. Ambil data asli & Lengkapi jadi 12-lead
                    java.util.List<double[]> rawLeads = parent.getProcessedLeadsData();
                    java.util.List<double[]> full12Leads = parent.generate12LeadData(rawLeads);

                    // 2. BUNGKUS SEMUA DATA KE DALAM Map UNTUK DIKIRIM KE PDF EXPORTER
                    java.util.Map<String, String> pdfData = new java.util.HashMap<>();

                    // -- Data untuk Tabel 1: Demografi Pasien
                    pdfData.put("name", (this.patientName != null && !this.patientName.isEmpty()) ? this.patientName : "-");
                    pdfData.put("id", (this.patientID != null && !this.patientID.isEmpty()) ? this.patientID : "-");
                    pdfData.put("age", String.valueOf(this.patientAge));
                    pdfData.put("dob", this.patientBirthdate != null ? this.patientBirthdate : "-");
                    pdfData.put("sex", this.patientSex != null ? this.patientSex : "-");

                    // -- Data untuk Tabel 2: Hasil Analisis Model
                    String deskripsiPanjang = projectecg.GeminiHealthAdvisor.getClassificationDescription(this.classificationResult);
                    pdfData.put("hr", this.heartRateAvg > 0 ? String.format("%.1f", this.heartRateAvg) : "-");
                    pdfData.put("diagnosis", deskripsiPanjang);
                    pdfData.put("confidence", String.format("%.1f", this.confidenceRate * 100));
                    pdfData.put("risk", this.riskLevel != null ? this.riskLevel : "-");

                    // -- Data untuk Tabel 3: Metrics (Mengambil data dari TextBox UI)
                    pdfData.put("rrAvg", jTextField5.getText());
                    pdfData.put("rrMin", jTextField6.getText());
                    pdfData.put("rrMax", jTextField7.getText());
                    
                    pdfData.put("rPeaks", jTextField8.getText());
                    pdfData.put("pPeaks", jTextField9.getText());
                    pdfData.put("tPeaks", jTextField10.getText());
                    
                    pdfData.put("prAvg", jTextField11.getText());
                    pdfData.put("qrsAvg", jTextField12.getText());
                    pdfData.put("qtAvg", jTextField13.getText());
                    pdfData.put("qtcAvg", jTextField14.getText());
                    
                    pdfData.put("prSeg", jTextFieldPR.getText());
                    pdfData.put("stInt", jTextFieldSTInterval.getText());
                    pdfData.put("stSeg", jTextFieldSTSegment.getText());
                    
                    pdfData.put("sdnn", jtxtSDNN.getText());
                    pdfData.put("rmssd", jtxtRMSSD.getText());
                    pdfData.put("nn50", jtxtNN50.getText());
                    pdfData.put("pnn50", jtxtpNN50.getText());
                    pdfData.put("sd1", jtxtSD1.getText());
                    pdfData.put("sd2", jtxtSD2.getText());

                    // Ambil data yang dipilih
                    String formulaName = parent.qtcFormula != null ? parent.qtcFormula : "Bazett";
                    pdfData.put("formula", formulaName);
                    pdfData.put("speed", parent.getSpeedSetting());
                    pdfData.put("gain", parent.getGainSetting());
                    pdfData.put("filter", parent.getFilterSetting());

                    // Kirim Saran Kesehatan mentah (Disclaimer akan otomatis dibuang oleh Exporter)
                    pdfData.put("advice", generateHealthAdvice());

                    // 3. Panggil PDFExporter dengan Map
                    boolean success = projectecg.PDFExporter.generateReport(
                        filePath, pdfData, full12Leads, parent.getCurrentFs()
                    );
                    
                    if (success) {
                        javax.swing.JOptionPane.showMessageDialog(this, "✓ Laporan PDF medis berhasil disimpan ke:\n" + filePath, "Export Successful", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                    } else {
                        javax.swing.JOptionPane.showMessageDialog(this, "Gagal membuat PDF. Pastikan file tidak sedang dibuka.", "Export Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
                    }
                } catch (Exception e) {
                    e.printStackTrace();
                    javax.swing.JOptionPane.showMessageDialog(this, "Terjadi kesalahan sistem saat mengekspor ke PDF.", "Export Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        }
    }

