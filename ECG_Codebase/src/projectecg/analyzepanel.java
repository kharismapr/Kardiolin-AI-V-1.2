    private void colorCodeSTSegment(double stValue) {
        if (jTextFieldSTSegment == null) return;
        
        // Indikator warna klinis untuk deviasi segmen ST
        if (stValue >= 0.1) {
            jTextFieldSTSegment.setBackground(new java.awt.Color(255, 205, 205)); // Warna merah untuk Elevasi (STEMI)
            jTextFieldSTSegment.setForeground(new java.awt.Color(180, 0, 0));
            jTextFieldSTSegment.setToolTipText("ST Elevation (>= 0.1 mV / 1 mm): Potensi STEMI / Infark Miokard Akut!");
        } else if (stValue <= -0.1) {
            // ST Depression lebih dari 1 mm (kritis)
            jTextFieldSTSegment.setBackground(new java.awt.Color(255, 220, 180)); // Orange muda
            jTextFieldSTSegment.setForeground(new java.awt.Color(200, 80, 0));
            jTextFieldSTSegment.setToolTipText("ST Depression (> 1.0 mm / 0.1 mV): Potensi Iskemia Berat / NSTEMI!");
        } else if (stValue <= -0.05) {
            // ST Depression ringan (0.5 mm - 1.0 mm)
            jTextFieldSTSegment.setBackground(new java.awt.Color(215, 230, 255)); // Biru muda
            jTextFieldSTSegment.setForeground(new java.awt.Color(0, 75, 180));
            jTextFieldSTSegment.setToolTipText("ST Depression Mild (0.5 mm s/d 1.0 mm): Potensi Iskemia Ringan.");
        } else {
            jTextFieldSTSegment.setBackground(new java.awt.Color(138, 242, 175)); // Warna hijau untuk Normal
            jTextFieldSTSegment.setForeground(new java.awt.Color(50, 50, 50));
            jTextFieldSTSegment.setToolTipText("ST Amplitude Normal (-0.05 mV s/d 0.1 mV)");
        }
    }

