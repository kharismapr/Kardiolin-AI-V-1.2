    public void setPatientInfo(String name, String id, String classification, double confidence, String riskLevel) {
        this.patientName = (name != null && !name.trim().isEmpty()) ? name : "N/A";
        this.patientID = (id != null && !id.trim().isEmpty()) ? id : "N/A";
        this.classificationResult = (classification != null && !classification.trim().isEmpty()) ? classification : "N/A";
        
        // Normalisasi confidence rate (0.0 - 1.0)
        if (confidence < 0) {
            this.confidenceRate = 0;
        } else if (confidence > 1) {
            this.confidenceRate = confidence > 100 ? 1.0 : confidence / 100.0;
        } else {
            this.confidenceRate = confidence;
        }
        
        this.riskLevel = (riskLevel != null && !riskLevel.trim().isEmpty()) ? riskLevel : "Unknown";
    }
    
    public void setPatientInfoComplete(String name, String id, String sex, String birthdate, 
                                       String ageStr,
                                       String classification, double confidence, String riskLevel) {
        setPatientInfo(name, id, classification, confidence, riskLevel);
        this.patientSex = (sex != null && !sex.trim().isEmpty()) ? sex : "N/A";
        this.patientBirthdate = (birthdate != null && !birthdate.trim().isEmpty()) ? birthdate : "N/A";
        
        // Parsing angka demografis pasien secara aman
        this.patientAge = parsePositiveInt(ageStr, 0, 150);
    }
    
    private int parsePositiveInt(String value, int min, int max) {
        if (value == null || value.trim().isEmpty()) return 0;
        try {
            int parsed = Integer.parseInt(value.trim());
            return (parsed >= min && parsed <= max) ? parsed : 0;
        } catch (NumberFormatException e) {
            try {
                double parsed = Double.parseDouble(value.trim());
                int intVal = (int) parsed;
                return (intVal >= min && intVal <= max) ? intVal : 0;
            } catch (NumberFormatException e2) {
                return 0;
            }
        }
    }
    
