    private void juploadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event-juploadActionPerformed
    // ═══════════════════════════════════════════════════════════════════════════════════════════════════════════
    // STATE MANAGEMENT: Upload CSV → Enable Analyze Button
    // RULE 1: Analyze button starts DISABLED (set in constructor)
    // RULE 2: After successful CSV upload, Analyze becomes ENABLED
    // RULE 3: Works in BOTH modes - Diagnose Mode (Import CSV) and Monitoring Mode (Real-time Recording)
    // ═══════════════════════════════════════════════════════════════════════════════════════════════════════════
    
    JFileChooser chooser = new JFileChooser();
    FileNameExtensionFilter filter = new FileNameExtensionFilter("CSV Files", "csv");
    chooser.setFileFilter(filter);

    int returnVal = chooser.showOpenDialog(this);
    if (returnVal == JFileChooser.APPROVE_OPTION) {
        File file = chooser.getSelectedFile();

        try {
            BufferedReader br = new BufferedReader(new FileReader(file));
            String line;
            
            // Variabel sementara untuk menampung data per kolom
            // List didalam List (Baris -> Kolom)
            ArrayList<ArrayList<Double>> tempColumns = new ArrayList<>();

            // Baca Header untuk tahu ada berapa kolom
            String header = br.readLine();
            if (header != null) {
                String[] cols = header.split(",");
                // Siapkan arraylist untuk setiap kolom data (mulai index 1 karena index 0 biasanya timestamp)
                for (int i = 1; i < cols.length; i++) {
                    tempColumns.add(new ArrayList<>());
                }
            }

            // Baca Isi Data
            while ((line = br.readLine()) != null) {
                String[] values = line.split(",");
                
                // Loop setiap kolom mulai dari index 1 (asumsi index 0 adalah waktu)
                for (int i = 1; i < values.length; i++) {
                    // Pastikan kolom tersedia di tempColumns
                    if ((i - 1) < tempColumns.size()) {
                        try {
                            double val = Double.parseDouble(values[i]);
                            tempColumns.get(i - 1).add(val);
                        } catch (NumberFormatException e) {
                            tempColumns.get(i - 1).add(0.0); // Default jika error parsing
                        }
                    }
                }
            }
            br.close();

            // KONVERSI KE STRUKTUR UTAMA (leadsData)
            leadsData.clear(); // Bersihkan data lama
            for (ArrayList<Double> colData : tempColumns) {
                double[] primitiveArr = new double[colData.size()];
                for (int i = 0; i < colData.size(); i++) {
                    primitiveArr[i] = colData.get(i);
                }
                leadsData.add(primitiveArr);
            }

           // === START REVISI TOTAL (GANTIKAN KODE LAMA DENGAN INI) ===
            
            // 1. Reset Status & Pointer Data
            isFileLoaded = true;
            currentDataIndex = 0; // Mulai baca CSV dari baris pertama
            xGraph = 0;           // Mulai gambar dari sisi kiri panel

            // 2. Reset Baseline Grafik
            // Mencegah garis melompat/melintang saat transisi data
            int h = jPanel_ecgsignal.getHeight();
            for (int i = 0; i < 12; i++) {
                lastY[i] = h / 2; // Set posisi awal garis di tengah-tengah baris
            }

            // 3. Hard Reset Tampilan (Solusi Anti-Lag/Bayangan)
            resetBackground();         // Menghapus coretan hijau data lama
            jPanel_ecgsignal.repaint(); // Menggambar ulang grid bersih secara instan

            // 4. Update UI & Informasi File
            jlblStatus.setText("FILE LOADED: " + file.getName() + " (" + leadsData.size() + " Leads)");
            btnAnalyze.setToolTipText("Click to run Model Classification");

            // 5. Jalankan Engine Analisis Background
            recalculateFilters(); // Hitung filter digital sesuai setting
            updateWaveMarkers();  // Cari P, Q, R, S, T untuk visualisasi
            enforceButtonState(); // Tentukan tombol Analyze nyala/mati sesuai mode
            updateAutoHR();       // Hitung Heart Rate awal

            // === END REVISI TOTAL ===
        } catch (Exception e) {
            System.out.println("Error reading CSV: " + e.getMessage());
            e.printStackTrace();
            jlblStatus.setText("ERROR LOADING FILE");
        }
    }
    }//GEN-LAST:event-juploadActionPerformed

    private void jrecordActionPerformed(java.awt.event.ActionEvent evt) {
        Object selectedItem = jComboBox_port.getSelectedItem();
        if (selectedItem == null) return;
        String portName = selectedItem.toString();

        if (jrecord.isSelected()) {
            // === START RECORDING ===
            try {
                // 1. Clear Queues & Data
                queueByte.clear();
                queueString.clear();
                leadsData.clear();
                processedData.clear();
                for(int i=0; i<12; i++) {
                leadsData.add(new double[MAX_SAMPLE]);
                processedData.add(new double[MAX_SAMPLE]);
                }
                writeIndex = 0;
                currentDataIndex = 0;

                // 2. Init & Open Serial Comm (The Ear)
                // 115200 is standard for this specific DAQ firmware usually
                serialComm = new SerialCommBiner(portName, 115200, queueByte); 
                serialComm.openPortEvent(); // Starts listening to bytes

                if (serialComm.isOpen()) {
                    // 3. Init & Start Parser (The Brain)
                    parserRunnable = new ThrdParsingECG(this, queueByte, queueString);
                    parsingThread = new Thread(parserRunnable);
                    parsingThread.start();

                    // 4. Start Consumer Timer (To update Dashboard from Queue)
                    // Reads from queueString every 10ms
                    consumerTimer = new javax.swing.Timer(10, e -> processParsedData());
                    consumerTimer.start();

                    jlblStatus.setText("Connected: " + portName);
                    jrecord.setText("STOP");
                    btnAnalyze.setEnabled(false);
                    isFileLoaded = true;
                } else {
                    jrecord.setSelected(false);
                    javax.swing.JOptionPane.showMessageDialog(this, "Failed to open port.");
                }
            } catch (Exception e) {
                e.printStackTrace();
                jrecord.setSelected(false);
            }

        } else {
            // === STOP RECORDING ===
            // 1. Stop Serial
            try {
                if (serialComm != null) serialComm.closePort();
            } catch (Exception e) {}
            
            // 2. Stop Parser
            if (parserRunnable != null) parserRunnable.setExit();
            
            // 3. Stop Consumer Timer
            if (consumerTimer != null) consumerTimer.stop();

            jrecord.setText("Record");
            jlblStatus.setText("Recording Stopped.");
            trimArrays(); 
            enforceButtonState();
        }
    }//GEN-LAST:event-jrecordActionPerformed

