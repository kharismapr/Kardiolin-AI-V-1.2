class SerialPortReader implements SerialPortDataListener {

    @Override
    public int getListeningEvents() { 
        // Memberitahu library: "Panggil saya kalau ada data masuk"
        return SerialPort.LISTENING_EVENT_DATA_AVAILABLE; 
    }

    @Override
    public void serialEvent(SerialPortEvent event) {
        // Safety check: Pastikan eventnya benar data available
        if (event.getEventType() != SerialPort.LISTENING_EVENT_DATA_AVAILABLE) return;
        
        // Baca data byte yang masuk
        byte[] newData = new byte[serialPort.bytesAvailable()];
        int numRead = serialPort.readBytes(newData, newData.length);
        
        if (numRead > 0) {
            // Ubah byte ke String
            String receivedData = new String(newData);
            serialBuffer += receivedData; 

            // --- LOGIKA PARSING DATA (Split per baris) ---
            int lineEndIndex;
            // Selama ada karakter "Enter" (\n), berarti ada satu baris data utuh
            while ((lineEndIndex = serialBuffer.indexOf("\n")) != -1) {
                // Ambil satu baris bersih
                String line = serialBuffer.substring(0, lineEndIndex).trim();
                // Buang baris itu dari buffer (biar gak dibaca ulang)
                serialBuffer = serialBuffer.substring(lineEndIndex + 1);

                // Pisahkan data CSV (titik koma)
                String[] values = line.split(";"); 
                
                // Pastikan tombol Record aktif dan data lengkap 12 kolom
                if (values.length == 12 && jrecord.isSelected()) {
                    if (writeIndex < MAX_SAMPLE) {
                        for (int i = 0; i < 12; i++) {
                            try {
                                double val = Double.parseDouble(values[i]);
                                leadsData.get(i)[writeIndex] = val;
                                processedData.get(i)[writeIndex] = val;
                            } catch (NumberFormatException e) { 
                                // Abaikan jika data corrupt/bukan angka
                            }
                        }
                        // Geser index array ke kanan setelah 1 baris (12 lead) selesai direkam
                        writeIndex++;
                    }
                }
            } // End While Loop
        }
    }
}
