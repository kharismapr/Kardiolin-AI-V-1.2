    private void jbtnDownloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event-jbtnDownloadActionPerformed
        // ════════════════════════════════════════════════════════════════════════════════════════════
        // DOWNLOAD ECG SIGNAL: Export recorded/uploaded ECG data to CSV file
        // PURPOSE: Allows user to save 12-lead ECG data for external analysis or archiving
        // SUPPORTS: Both real-time recorded data and uploaded CSV file data
        // ════════════════════════════════════════════════════════════════════════════════════════════
        
        // 1. VALIDATE: Check if ECG data exists
        if (leadsData == null || leadsData.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "No ECG data to download!\n\nPlease either:\n• Upload a CSV file, or\n• Record data from serial port first.",
                "No Data Available", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Check if data has actual samples
        int sampleCount = leadsData.get(0).length;
        if (sampleCount == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "ECG data is empty. Please record or upload data first.",
                "Empty Data", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // 2. ASK USER: Export raw, processed, or both?
        String[] options = {"Raw Signal", "Filtered Signal", "Both Files", "Cancel"};
        int choice = javax.swing.JOptionPane.showOptionDialog(this,
            "Which data would you like to export?\n\n" +
            "• Raw Signal: Original unfiltered ECG data\n" +
            "• Filtered Signal: Data with applied filters (Bandpass, Notch, etc.)\n" +
            "• Both Files: Export both raw and filtered as separate files",
            "Select Export Type",
            javax.swing.JOptionPane.DEFAULT_OPTION,
            javax.swing.JOptionPane.QUESTION_MESSAGE,
            null, options, options[1]);
        
        if (choice == 3 || choice == javax.swing.JOptionPane.CLOSED_OPTION) {
            return; // User cancelled
        }
        
        // choice: 0 = Raw, 1 = Filtered, 2 = Both
        
        // 3. FILE CHOOSER: Let user select save location
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Save ECG Data as CSV");
        
        // Generate default filename with patient ID and timestamp
        String patientID = jtxtID.getText().trim();
        String timestamp = new java.text.SimpleDateFormat("yyyyMMdd_HHmmss").format(new java.util.Date());
        String baseFilename = "ECG_" + (patientID.isEmpty() ? "Unknown" : patientID) + "_" + timestamp;
        
        // For "Both" option, use base name without suffix
        String defaultFilename = (choice == 2) ? baseFilename + "_raw.csv" : baseFilename + ".csv";
        fileChooser.setSelectedFile(new File(defaultFilename));
        
        // Set file filter to CSV
        FileNameExtensionFilter csvFilter = new FileNameExtensionFilter("CSV Files (*.csv)", "csv");
        fileChooser.setFileFilter(csvFilter);
        
        int userSelection = fileChooser.showSaveDialog(this);
        
        if (userSelection != JFileChooser.APPROVE_OPTION) {
            return; // User cancelled file dialog
        }
        
        // 4. GET FILE PATH: Ensure .csv extension
        File fileToSave = fileChooser.getSelectedFile();
        String filePath = fileToSave.getAbsolutePath();
        if (filePath.toLowerCase().endsWith(".csv")) {
            filePath = filePath.substring(0, filePath.length() - 4); // Remove .csv for base path
        }
        
        String patientName = txtname.getText().trim();
        boolean success = false;
        String resultMessage = "";
        
        // 5. EXPORT BASED ON CHOICE
        if (choice == 2) {
            // === BOTH FILES: Export raw and filtered separately ===
            File rawFile = new File(filePath + "_raw.csv");
            File filteredFile = new File(filePath + "_filtered.csv");
            
            // Check overwrite for both files
            if (rawFile.exists() || filteredFile.exists()) {
                int overwrite = javax.swing.JOptionPane.showConfirmDialog(this,
                    "One or both files already exist. Overwrite?",
                    "Confirm Overwrite",
                    javax.swing.JOptionPane.YES_NO_OPTION);
                if (overwrite != javax.swing.JOptionPane.YES_OPTION) {
                    return;
                }
            }

           


            // Export Raw Signal
            boolean rawSuccess = CSVExporter.exportSignalToCSV(
                rawFile, leadsData, currentFs, patientID, patientName);
            
            // Export Filtered Signal
            boolean filteredSuccess = CSVExporter.exportSignalToCSV(
                filteredFile, processedData, currentFs, patientID, patientName);
            
            success = rawSuccess && filteredSuccess;
            
            if (success) {
                resultMessage = "Both ECG files exported successfully!\n\n" +
                    "Raw File: " + rawFile.getName() + "\n" +
                    "Filtered File: " + filteredFile.getName() + "\n" +
                    "Location: " + rawFile.getParent() + "\n" +
                    "Samples: " + sampleCount + "\n" +
                    "Duration: " + String.format("%.2f", sampleCount / currentFs) + " seconds";
            } else {
                resultMessage = "Export partially failed.\n" +
                    "Raw: " + (rawSuccess ? "Success" : "Failed") + "\n" +
                    "Filtered: " + (filteredSuccess ? "Success" : "Failed");
            }
        } else {
            // === SINGLE FILE: Export raw OR filtered ===
            fileToSave = new File(filePath + ".csv");
            
            // Confirm overwrite if file exists
            if (fileToSave.exists()) {
                int overwrite = javax.swing.JOptionPane.showConfirmDialog(this,
                    "File already exists. Overwrite?",
                    "Confirm Overwrite",
                    javax.swing.JOptionPane.YES_NO_OPTION);
                if (overwrite != javax.swing.JOptionPane.YES_OPTION) {
                    return;
                }
            }
            
            boolean exportProcessed = (choice == 1); // 0 = Raw, 1 = Filtered
            java.util.List<double[]> dataToExport = exportProcessed ? processedData : leadsData;
            
            success = CSVExporter.exportSignalToCSV(
                fileToSave, dataToExport, currentFs, patientID, patientName);
            
            String dataType = exportProcessed ? "Filtered" : "Raw";
            resultMessage = "ECG data exported successfully!\n\n" +
                "File: " + fileToSave.getAbsolutePath() + "\n" +
                "Type: " + dataType + " Signal\n" +
                "Samples: " + sampleCount + "\n" +
                "Duration: " + String.format("%.2f", sampleCount / currentFs) + " seconds";
        }
        
        // 6. SHOW RESULT: Success or failure message
        if (success) {
            javax.swing.JOptionPane.showMessageDialog(this,
                resultMessage,
                "Export Successful",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Failed to export ECG data.\nPlease check file permissions and try again.",
                "Export Failed",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event-jbtnDownloadActionPerformed

